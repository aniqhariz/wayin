/**
 * Accessibility scoring per WAYIN guidelines:
 * Ramp: +40, No stairs: +30, Good condition: +15, Verified: +10, Near parking: +5
 */
export function calculateAccessScore(point: {
  type: AccessPointType;
  condition: 'good' | 'fair' | 'poor';
  verification: 'verified' | 'unverified' | 'reported';
  hasNoStairs: boolean;
  nearAccessibleParking: boolean;
}): number {
  let score = 0;
  if (point.type === 'ramp') score += 40;
  if (point.hasNoStairs) score += 30;
  if (point.condition === 'good') score += 15;
  if (point.verification === 'verified') score += 10;
  if (point.nearAccessibleParking) score += 5;
  return score;
}

